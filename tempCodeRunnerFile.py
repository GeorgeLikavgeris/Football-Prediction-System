from pathlib import Path

import pandas as pd
import streamlit as st

# --------------------------------
# PAGE CONFIG
# --------------------------------

st.set_page_config(
    page_title="Football Predictions Dashboard",
    page_icon="⚽",
    layout="wide",
)

st.title("⚽ Football Predictions Dashboard")
st.caption("Poisson-based match predictions from the latest available team results.")

# --------------------------------
# CONFIGURATION
# --------------------------------

BASE_DIR = Path(__file__).resolve().parent
DATA_FILE = BASE_DIR / "data" / "predictions_all.csv"

REQUIRED_COLUMNS = [
    "league",
    "home_team",
    "away_team",
    "ft_exp_home",
    "ft_exp_away",
    "ft_home_win",
    "ft_draw",
    "ft_away_win",
    "ft_over_2_5",
    "ft_under_2_5",
    "ht_home_win",
    "ht_draw",
    "ht_away_win",
    "ht_over_0_5",
    "ht_under_0_5",
    "ht_exp_home",
    "ht_exp_away",
]

PROBABILITY_COLUMNS = [
    "ft_home_win",
    "ft_draw",
    "ft_away_win",
    "ft_over_2_5",
    "ft_under_2_5",
    "ht_home_win",
    "ht_draw",
    "ht_away_win",
    "ht_over_0_5",
    "ht_under_0_5",
]

EXPECTED_GOAL_COLUMNS = [
    "ft_exp_home",
    "ft_exp_away",
    "ht_exp_home",
    "ht_exp_away",
]


# --------------------------------
# LOAD DATA
# --------------------------------

@st.cache_data
def load_data(file_path: str, modified_time: float) -> pd.DataFrame:
    """Load predictions from CSV. modified_time refreshes the cache after updates."""
    del modified_time  # Used as a cache key; the file is read below.
    return pd.read_csv(file_path)


if not DATA_FILE.exists():
    st.error(f"Predictions file was not found: `{DATA_FILE}`")
    st.info(
        "Run `predict_matches.py` first so it can create "
        "`data/predictions_all.csv`."
    )
    st.stop()

try:
    df = load_data(str(DATA_FILE), DATA_FILE.stat().st_mtime)
except (OSError, pd.errors.EmptyDataError, pd.errors.ParserError) as exc:
    st.error(f"Could not read the predictions CSV: {exc}")
    st.stop()

if df.empty:
    st.warning("The predictions CSV exists, but it contains no rows.")
    st.stop()

missing_columns = [column for column in REQUIRED_COLUMNS if column not in df.columns]
if missing_columns:
    st.error(
        "The predictions CSV is missing required columns: "
        + ", ".join(f"`{column}`" for column in missing_columns)
    )
    st.info(
        "Check that `predict_matches.py` writes the same column names expected "
        "by this dashboard."
    )
    st.stop()

# Remove rows that cannot be displayed as a fixture.
df = df.dropna(subset=["league", "home_team", "away_team"]).copy()

if df.empty:
    st.warning("No usable fixtures were found in the predictions CSV.")
    st.stop()

# Standardize text fields and convert prediction fields to numeric values.
for column in ["league", "home_team", "away_team"]:
    df[column] = df[column].astype(str).str.strip()

for column in PROBABILITY_COLUMNS + EXPECTED_GOAL_COLUMNS:
    df[column] = pd.to_numeric(df[column], errors="coerce")

df = df.dropna(subset=EXPECTED_GOAL_COLUMNS + PROBABILITY_COLUMNS).copy()

if df.empty:
    st.warning(
        "No rows have complete numeric prediction values. "
        "Check the output generated by `predict_matches.py`."
    )
    st.stop()

# Avoid displaying invalid probability values as if they were valid percentages.
invalid_probabilities = (
    (df[PROBABILITY_COLUMNS] < 0) | (df[PROBABILITY_COLUMNS] > 100)
).any(axis=1)

if invalid_probabilities.any():
    st.warning(
        f"{int(invalid_probabilities.sum())} row(s) contain probability values "
        "outside the expected 0–100 range. These rows are excluded from the dashboard."
    )
    df = df.loc[~invalid_probabilities].copy()

if df.empty:
    st.warning("No rows remain after validating the probability values.")
    st.stop()

# --------------------------------
# LEAGUE FILTER
# --------------------------------

leagues = sorted(df["league"].dropna().unique().tolist())

if not leagues:
    st.warning("No leagues are available in the predictions CSV.")
    st.stop()

league = st.selectbox("Select League", leagues)

league_df = df.loc[df["league"] == league].copy()
league_df["match"] = (
    league_df["home_team"].astype(str) + " vs " + league_df["away_team"].astype(str)
)

# Keep the selection labels unique if duplicate fixtures exist in the CSV.
league_df["match_label"] = league_df["match"]
if league_df["match_label"].duplicated().any():
    league_df["match_label"] = (
        league_df["match"]
        + " — row "
        + (league_df.groupby("match").cumcount() + 1).astype(str)
    )

# --------------------------------
# MATCH FILTER
# --------------------------------

if league_df.empty:
    st.warning("There are no fixtures available for this league.")
    st.stop()

selected_label = st.selectbox("Select Match", league_df["match_label"].tolist())
match_data = league_df.loc[league_df["match_label"] == selected_label].iloc[0]

home = str(match_data["home_team"])
away = str(match_data["away_team"])

st.header(f"{home} vs {away}")

# --------------------------------
# DISPLAY HELPERS
# --------------------------------

def show_probability(value) -> str:
    """Format a probability stored on a 0–100 scale."""
    if pd.isna(value):
        return "N/A"
    return f"{value:.1f}%"


def show_goals(value) -> str:
    """Format expected goals."""
    if pd.isna(value):
        return "N/A"
    return f"{value:.2f}"


# --------------------------------
# TABS
# --------------------------------

tab1, tab2, tab3 = st.tabs(
    [
        "📊 Overview",
        "⚽ Full Time",
        "⏱ Half Time",
    ]
)

# =================================
# TAB 1 - OVERVIEW
# =================================

with tab1:
    st.subheader("Expected Goals")

    col1, col2 = st.columns(2)
    col1.metric(home, show_goals(match_data["ft_exp_home"]))
    col2.metric(away, show_goals(match_data["ft_exp_away"]))

    st.markdown("---")
    st.subheader("Full-Time Match Probabilities")

    col1, col2, col3 = st.columns(3)
    col1.metric("Home Win", show_probability(match_data["ft_home_win"]))
    col2.metric("Draw", show_probability(match_data["ft_draw"]))
    col3.metric("Away Win", show_probability(match_data["ft_away_win"]))

    st.markdown("---")
    st.subheader("Full-Time Over / Under 2.5 Goals")

    col1, col2 = st.columns(2)
    col1.metric("Over 2.5", show_probability(match_data["ft_over_2_5"]))
    col2.metric("Under 2.5", show_probability(match_data["ft_under_2_5"]))

    st.markdown("---")
    st.subheader("Half-Time Summary")

    col1, col2, col3 = st.columns(3)
    col1.metric("Home Win (HT)", show_probability(match_data["ht_home_win"]))
    col2.metric("Draw (HT)", show_probability(match_data["ht_draw"]))
    col3.metric("Away Win (HT)", show_probability(match_data["ht_away_win"]))

    col1, col2 = st.columns(2)
    col1.metric("Over 0.5 Goals (HT)", show_probability(match_data["ht_over_0_5"]))
    col2.metric("Under 0.5 Goals (HT)", show_probability(match_data["ht_under_0_5"]))


# =================================
# TAB 2 - FULL TIME
# =================================

with tab2:
    st.subheader("Full-Time Result Probabilities")

    col1, col2, col3 = st.columns(3)
    col1.metric(home, show_probability(match_data["ft_home_win"]))
    col2.metric("Draw", show_probability(match_data["ft_draw"]))
    col3.metric(away, show_probability(match_data["ft_away_win"]))

    st.markdown("---")
    st.subheader("Over / Under 2.5 Goals")

    col1, col2 = st.columns(2)
    col1.metric("Over 2.5", show_probability(match_data["ft_over_2_5"]))
    col2.metric("Under 2.5", show_probability(match_data["ft_under_2_5"]))

    st.markdown("---")
    st.subheader("Expected Goals")

    col1, col2 = st.columns(2)
    col1.metric(home, show_goals(match_data["ft_exp_home"]))
    col2.metric(away, show_goals(match_data["ft_exp_away"]))


# =================================
# TAB 3 - HALF TIME
# =================================

with tab3:
    st.subheader("Half-Time Result Probabilities")

    col1, col2, col3 = st.columns(3)
    col1.metric(home, show_probability(match_data["ht_home_win"]))
    col2.metric("Draw", show_probability(match_data["ht_draw"]))
    col3.metric(away, show_probability(match_data["ht_away_win"]))

    st.markdown("---")
    st.subheader("Over / Under 0.5 Goals (Half Time)")

    col1, col2 = st.columns(2)
    col1.metric("Over 0.5", show_probability(match_data["ht_over_0_5"]))
    col2.metric("Under 0.5", show_probability(match_data["ht_under_0_5"]))

    st.markdown("---")
    st.subheader("Expected Goals (Half Time)")

    col1, col2 = st.columns(2)
    col1.metric(home, show_goals(match_data["ht_exp_home"]))
    col2.metric(away, show_goals(match_data["ht_exp_away"]))


# =================================
# FULL TABLE
# =================================

st.markdown("---")
st.subheader("All Matches — League View")

display_df = league_df.drop(columns=["match", "match_label"], errors="ignore").copy()

# Format prediction columns for easier reading in the table.
for column in PROBABILITY_COLUMNS:
    display_df[column] = display_df[column].map(show_probability)

for column in EXPECTED_GOAL_COLUMNS:
    display_df[column] = display_df[column].map(show_goals)

st.dataframe(display_df, use_container_width=True, hide_index=True)

st.caption(
    "Probabilities are model estimates, not guarantees. "
    "Please check the model output and underlying data before drawing conclusions."
)
